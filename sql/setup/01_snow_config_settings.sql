-- Run ONCE, manually, with an administrative role. NOT run by CI.

USE ROLE ACCOUNTADMIN;

-- 1. COMPUTE
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 2. DATABASE & SCHEMA
CREATE DATABASE IF NOT EXISTS ECON_DB;
CREATE SCHEMA IF NOT EXISTS ECON_DB.ANALYTICS;

-- 3. ROLE
CREATE ROLE IF NOT EXISTS ECON_ROLE;

-- 4. DATABASE & SCHEMA PRIVILEGES
GRANT USAGE ON DATABASE ECON_DB TO ROLE ECON_ROLE;
GRANT USAGE ON SCHEMA ECON_DB.ANALYTICS TO ROLE ECON_ROLE;
GRANT CREATE TABLE         ON SCHEMA ECON_DB.ANALYTICS TO ROLE ECON_ROLE;
GRANT CREATE DYNAMIC TABLE ON SCHEMA ECON_DB.ANALYTICS TO ROLE ECON_ROLE;
GRANT CREATE PROCEDURE     ON SCHEMA ECON_DB.ANALYTICS TO ROLE ECON_ROLE;
GRANT CREATE TASK          ON SCHEMA ECON_DB.ANALYTICS TO ROLE ECON_ROLE;

-- 5. WAREHOUSE & TASKS
GRANT USAGE, OPERATE ON WAREHOUSE COMPUTE_WH TO ROLE ECON_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE ECON_ROLE;

-- 6. EXTERNAL SHARED DATA
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_PUBLIC_DATA_FREE TO ROLE ECON_ROLE;

-- 7. BACK TO THE WORKING ROLE (objects created next belong to ECON_ROLE)
USE ROLE ECON_ROLE;