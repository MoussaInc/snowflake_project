-- Q2 : Analyse de l'évolution annuelle du chômage
-- Objectif : calculer le taux moyen annuel et sa variation relative
WITH yearly_unemployment AS (
SELECT
DATE_TRUNC('YEAR', DATE)::DATE AS YEAR,
AVG(VALUE) AS UNEMPLOYMENT_RATE
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
WHERE METRIC = 'UNEMPLOYMENT_RATE'
GROUP BY DATE_TRUNC('YEAR', DATE)::DATE
),
unemployment_with_previous_year AS (
SELECT
YEAR,
        UNEMPLOYMENT_RATE,
LAG(UNEMPLOYMENT_RATE, 1) OVER (ORDER BY YEAR) AS UNEMPLOYMENT_RATE_PREVIOUS_YEAR
FROM yearly_unemployment
)

SELECT
YEAR,
ROUND(UNEMPLOYMENT_RATE, 2) AS UNEMPLOYMENT_RATE,
ROUND(UNEMPLOYMENT_RATE_PREVIOUS_YEAR, 2) AS UNEMPLOYMENT_RATE_PREVIOUS_YEAR,
ROUND(100.0 * (UNEMPLOYMENT_RATE - UNEMPLOYMENT_RATE_PREVIOUS_YEAR) / NULLIF(UNEMPLOYMENT_RATE_PREVIOUS_YEAR, 0), 2) AS UNEMPLOYMENT_RATE_CHANGE_YOY_PCT,
ROUND(UNEMPLOYMENT_RATE - UNEMPLOYMENT_RATE_PREVIOUS_YEAR, 2) AS UNEMPLOYMENT_RATE_CHANGE_POINTS
FROM unemployment_with_previous_year
WHERE YEAR >= '1990-01-01'
ORDER BY YEAR;


