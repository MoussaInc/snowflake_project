-- TEST 1 (Unicité des observations): une seule observation par date et par indicateur

SELECT
    DATE,
    METRIC,
    COUNT(*) AS OBSERVATION_COUNT
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
GROUP BY DATE, METRIC
HAVING COUNT(*) > 1
ORDER BY DATE, METRIC;


