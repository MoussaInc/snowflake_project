-- Q4 : Dernière observation disponible par indicateur
WITH ranked_observations AS (
SELECT
DATE,
        METRIC,
VALUE,
ROW_NUMBER() OVER (PARTITION BY METRIC ORDER BY DATE DESC) AS RANK
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
WHERE VALUE IS NOT NULL
)

SELECT
DATE,
    METRIC,
VALUE
FROM ranked_observations
WHERE RANK = 1;