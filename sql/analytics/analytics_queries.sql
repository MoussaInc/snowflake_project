-- Q1 : calculer l'évolution annuelle du CPI depuis 1990

WITH monthly_cpi AS (
SELECT
DATE_TRUNC('MONTH', DATE) AS MONTH,
AVG(VALUE) AS CPI
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
WHERE METRIC = 'CPI' AND DATE >= '1990-01-01'
GROUP BY DATE_TRUNC('MONTH', DATE)
),

cpi_with_previous_year AS (
SELECT
MONTH,
        CPI,
LAG(CPI, 12) OVER (ORDER BY MONTH) AS CPI_12_MONTHS_AGO
FROM monthly_cpi
)

SELECT
MONTH,
    CPI,
    CPI_12_MONTHS_AGO,
ROUND(100.0 * ((CPI - CPI_12_MONTHS_AGO) / NULLIF(CPI_12_MONTHS_AGO, 0)), 2) AS CPI_CHANGE_YOY_PCT
FROM cpi_with_previous_year
ORDER BY MONTH;

