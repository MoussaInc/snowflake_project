-- TEST 2 (valeurs anormales) - Hypothèse : les taux sont stockés sous forme décimale

SELECT
    DATE::DATE AS OBSERVATION_DATE,
    METRIC,
    VALUE,
    UNIT,
    CASE
        WHEN VALUE IS NULL THEN 'VALEUR_NULLE'
        WHEN METRIC = 'CPI' AND VALUE <= 0 THEN 'CPI_NON_POSITIF'
        WHEN METRIC = 'UNEMPLOYMENT_RATE' AND (VALUE < 0 OR VALUE > 1) THEN 'TAUX_CHOMAGE_HORS_PLAGE'
        WHEN METRIC = 'MORTGAGE_RATE_30Y' AND (VALUE < 0 OR VALUE > 1) THEN 'TAUX_HYPOTHECAIRE_HORS_PLAGE'
        ELSE 'A_VERIFIER'
    END AS ANOMALY_TYPE
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
WHERE VALUE IS NULL
    OR (METRIC = 'CPI' AND VALUE <= 0)
    OR (METRIC = 'UNEMPLOYMENT_RATE' AND (VALUE < 0 OR VALUE > 1))
    OR (METRIC = 'MORTGAGE_RATE_30Y' AND (VALUE < 0 OR VALUE > 1))
ORDER BY
    OBSERVATION_DATE,
    METRIC;


-- ============================================================
-- TEST 3 : Complétude des indicateurs

SELECT
    METRIC,
    COUNT(*) AS NB_LIGNES,
    COUNT(VALUE) AS NB_VALEURS_PRESENTES,
    COUNT(*) - COUNT(VALUE) AS NB_VALEURS_MANQUANTES,
    ROUND(100.0 * COUNT(VALUE) / NULLIF(COUNT(*), 0), 2) AS COMPLETUDE_PCT
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
GROUP BY METRIC
ORDER BY METRIC;


