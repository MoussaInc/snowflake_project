-- Q3 : Moyenne mobile des taux hypothécaires
-- Fenêtre : 5 observations

WITH mortgage_rates AS (
SELECT
DATE::DATE AS OBSERVATION_DATE,
VALUE::FLOAT AS MORTGAGE_RATE
FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
WHERE METRIC = 'MORTGAGE_RATE_30Y' AND VALUE IS NOT NULL
),
mortgage_moving_average AS (
SELECT
        OBSERVATION_DATE,
        MORTGAGE_RATE,
AVG(MORTGAGE_RATE) OVER (ORDER BY OBSERVATION_DATE ROWS BETWEEN 4 PRECEDING AND CURRENT ROW) AS MOVING_AVG_5_OBSERVATIONS
FROM mortgage_rates
)

SELECT
    OBSERVATION_DATE,
    MORTGAGE_RATE,
ROUND(MOVING_AVG_5_OBSERVATIONS, 4) AS MOVING_AVG_5_OBSERVATIONS
FROM mortgage_moving_average
ORDER BY OBSERVATION_DATE;

