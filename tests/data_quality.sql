-- TEST 4 : Cohérence temporelle des séries

WITH ordered_observations AS (
    SELECT
        METRIC,
        DATE::DATE AS OBSERVATION_DATE,
        LAG(DATE::DATE) OVER (PARTITION BY METRIC ORDER BY DATE::DATE) AS PREVIOUS_DATE
    FROM ECON_DB.ANALYTICS.ECONOMIC_DYNAMIC_TABLE
    WHERE DATE IS NOT NULL
),
date_gaps AS (
    SELECT
        METRIC,
        PREVIOUS_DATE,
        OBSERVATION_DATE,
        DATEDIFF(DAY, PREVIOUS_DATE, OBSERVATION_DATE) AS GAP_DAYS
    FROM ordered_observations
    WHERE PREVIOUS_DATE IS NOT NULL
)
SELECT
    METRIC,
    PREVIOUS_DATE,
    OBSERVATION_DATE,
    GAP_DAYS,
    CASE
        WHEN METRIC IN ('CPI', 'UNEMPLOYMENT_RATE') AND GAP_DAYS > 45 THEN 'ECART_MENSUEL_A_VERIFIER'
        WHEN METRIC = 'MORTGAGE_RATE_30Y' AND GAP_DAYS > 14 THEN 'ECART_HEBDOMADAIRE_A_VERIFIER'
        ELSE 'A_VERIFIER'
    END AS TEMPORAL_ISSUE
FROM date_gaps
WHERE (METRIC IN ('CPI', 'UNEMPLOYMENT_RATE') AND GAP_DAYS > 45)
    OR (METRIC = 'MORTGAGE_RATE_30Y' AND GAP_DAYS > 14)
ORDER BY METRIC, OBSERVATION_DATE;